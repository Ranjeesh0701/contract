use crate::ir::{Contract, EnumType, Record, Service, Type, TypeAlias, TypeDefinition};

pub struct GoGenerator;

impl GoGenerator {
    pub fn generate(contract: &Contract) -> String {
        let mut out = String::new();

        out.push_str("// Code generated by contract platform. DO NOT EDIT.\n\n");
        out.push_str("package client\n\n");

        let has_services = !contract.services.is_empty();

        if has_services {
            out.push_str("import (\n");
            out.push_str("\t\"bytes\"\n");
            out.push_str("\t\"context\"\n");
            out.push_str("\t\"encoding/json\"\n");
            out.push_str("\t\"fmt\"\n");
            out.push_str("\t\"io\"\n");
            out.push_str("\t\"net/http\"\n");
            out.push_str("\t\"strings\"\n");
            out.push_str(")\n\n");
        }

        if let Some(ref desc) = contract.description {
            out.push_str(&format!("// {}\n", desc));
        }

        for type_def in &contract.types {
            match type_def {
                TypeDefinition::Alias(alias) => Self::generate_alias(alias, &mut out),
                TypeDefinition::Enum(enm) => Self::generate_enum(enm, &mut out),
                TypeDefinition::Record(rec) => Self::generate_record(rec, &mut out),
            }
            out.push('\n');
        }

        for service in &contract.services {
            Self::generate_service(service, &mut out);
            out.push('\n');
        }

        if has_services {
            let client_name = format!("{}Client", to_pascal_case(&contract.name));
            out.push_str(&format!("type {} struct {{\n", client_name));
            for service in &contract.services {
                let field_name = to_pascal_case(&service.name);
                out.push_str(&format!("\t{} *{}Client\n", field_name, service.name));
            }
            out.push_str("}\n\n");

            out.push_str(&format!(
                "func New{}(baseURL string, httpClient *http.Client) *{} {{\n",
                client_name, client_name
            ));
            out.push_str(&format!("\treturn &{}{{\n", client_name));
            for service in &contract.services {
                let field_name = to_pascal_case(&service.name);
                out.push_str(&format!(
                    "\t\t{}: New{}Client(baseURL, httpClient),\n",
                    field_name, service.name
                ));
            }
            out.push_str("\t}\n}\n");
        }

        out
    }

    fn generate_alias(alias: &TypeAlias, out: &mut String) {
        if let Some(ref desc) = alias.description {
            out.push_str(&format!("// {}\n", desc));
        }
        out.push_str(&format!(
            "type {} = {}\n",
            alias.name,
            Self::type_to_go(&alias.target)
        ));
    }

    fn generate_enum(enm: &EnumType, out: &mut String) {
        if let Some(ref desc) = enm.description {
            out.push_str(&format!("// {}\n", desc));
        }
        out.push_str(&format!("type {} string\n\n", enm.name));
        out.push_str("const (\n");

        for variant in &enm.variants {
            if let Some(ref desc) = variant.description {
                out.push_str(&format!("\t// {}\n", desc));
            }
            out.push_str(&format!(
                "\t{}{} {} = \"{}\"\n",
                enm.name, variant.name, enm.name, variant.name
            ));
        }

        out.push_str(")\n");
    }

    fn generate_record(rec: &Record, out: &mut String) {
        if let Some(ref desc) = rec.description {
            out.push_str(&format!("// {}\n", desc));
        }
        out.push_str(&format!("type {} struct {{\n", rec.name));

        for field in &rec.fields {
            if let Some(ref desc) = field.description {
                out.push_str(&format!("\t// {}\n", desc));
            }

            let field_ident = to_pascal_case(&field.name);
            let go_type = Self::type_to_go(&field.field_type);
            let is_optional = matches!(field.field_type, Type::Optional(_));

            let tag = if is_optional {
                format!("`json:\"{},omitempty\"`", field.name)
            } else {
                format!("`json:\"{}\"`", field.name)
            };

            out.push_str(&format!("\t{} {} {}\n", field_ident, go_type, tag));
        }

        out.push_str("}\n");
    }

    fn generate_service(service: &Service, out: &mut String) {
        // Interface
        if let Some(ref desc) = service.description {
            out.push_str(&format!("// {}\n", desc));
        }
        out.push_str(&format!("type {} interface {{\n", service.name));

        for op in &service.operations {
            if let Some(ref desc) = op.description {
                out.push_str(&format!("\t// {}\n", desc));
            }

            let method_name = to_pascal_case(&op.name);
            let input_param = match &op.input {
                Some(ty) => format!(", input {}", Self::type_to_go(ty)),
                None => "".to_string(),
            };

            let output_type = match &op.output {
                Some(ty) => {
                    let t = Self::type_to_go(ty);
                    if matches!(ty, Type::Reference(_)) {
                        format!("*{}", t)
                    } else {
                        t
                    }
                }
                None => "".to_string(),
            };

            if output_type.is_empty() {
                out.push_str(&format!(
                    "\t{}(ctx context.Context{}) error\n",
                    method_name, input_param
                ));
            } else {
                out.push_str(&format!(
                    "\t{}(ctx context.Context{}) ({}, error)\n",
                    method_name, input_param, output_type
                ));
            }
        }
        out.push_str("}\n\n");

        // Concrete Client
        let client_name = format!("{}Client", service.name);
        out.push_str(&format!("type {} struct {{\n", client_name));
        out.push_str("\tbaseURL    string\n");
        out.push_str("\thttpClient *http.Client\n");
        out.push_str("}\n\n");

        out.push_str(&format!(
            "func New{}(baseURL string, httpClient *http.Client) *{} {{\n",
            client_name, client_name
        ));
        out.push_str("\tif httpClient == nil {\n");
        out.push_str("\t\thttpClient = http.DefaultClient\n");
        out.push_str("\t}\n");
        out.push_str(&format!("\treturn &{}{{\n", client_name));
        out.push_str("\t\tbaseURL:    strings.TrimRight(baseURL, \"/\"),\n");
        out.push_str("\t\thttpClient: httpClient,\n");
        out.push_str("\t}\n}\n\n");

        for (idx, op) in service.operations.iter().enumerate() {
            if idx > 0 {
                out.push('\n');
            }

            if let Some(ref desc) = op.description {
                out.push_str(&format!("// {}\n", desc));
            }

            let method_name = to_pascal_case(&op.name);
            let has_input = op.input.is_some();
            let input_param = if has_input {
                format!(", input {}", Self::type_to_go(op.input.as_ref().unwrap()))
            } else {
                "".to_string()
            };

            let output_type = match &op.output {
                Some(ty) => {
                    let t = Self::type_to_go(ty);
                    if matches!(ty, Type::Reference(_)) {
                        format!("*{}", t)
                    } else {
                        t
                    }
                }
                None => "".to_string(),
            };

            let sig_return = if output_type.is_empty() {
                "error".to_string()
            } else {
                format!("({}, error)", output_type)
            };

            out.push_str(&format!(
                "func (c *{}) {}(ctx context.Context{}) {} {{\n",
                client_name, method_name, input_param, sig_return
            ));
            out.push_str(&format!(
                "\turl := fmt.Sprintf(\"%s/{}/{}\", c.baseURL)\n",
                service.name, op.name
            ));

            if has_input {
                out.push_str("\tpayload, err := json.Marshal(input)\n");
                out.push_str("\tif err != nil {\n");
                if output_type.is_empty() {
                    out.push_str("\t\treturn fmt.Errorf(\"failed to marshal input: %w\", err)\n");
                } else {
                    out.push_str(
                        "\t\treturn nil, fmt.Errorf(\"failed to marshal input: %w\", err)\n",
                    );
                }
                out.push_str("\t}\n");
                out.push_str("\treq, err := http.NewRequestWithContext(ctx, http.MethodPost, url, bytes.NewReader(payload))\n");
            } else {
                out.push_str(
                    "\treq, err := http.NewRequestWithContext(ctx, http.MethodPost, url, nil)\n",
                );
            }

            out.push_str("\tif err != nil {\n");
            if output_type.is_empty() {
                out.push_str("\t\treturn fmt.Errorf(\"failed to create request: %w\", err)\n");
            } else {
                out.push_str("\t\treturn nil, fmt.Errorf(\"failed to create request: %w\", err)\n");
            }
            out.push_str("\t}\n");
            out.push_str("\treq.Header.Set(\"Content-Type\", \"application/json\")\n\n");

            out.push_str("\tresp, err := c.httpClient.Do(req)\n");
            out.push_str("\tif err != nil {\n");
            if output_type.is_empty() {
                out.push_str("\t\treturn fmt.Errorf(\"request failed: %w\", err)\n");
            } else {
                out.push_str("\t\treturn nil, fmt.Errorf(\"request failed: %w\", err)\n");
            }
            out.push_str("\t}\n");
            out.push_str("\tdefer resp.Body.Close()\n\n");

            out.push_str("\tif resp.StatusCode < 200 || resp.StatusCode >= 300 {\n");
            out.push_str("\t\tbody, _ := io.ReadAll(resp.Body)\n");
            if output_type.is_empty() {
                out.push_str(&format!(
                    "\t\treturn fmt.Errorf(\"{}.{} failed with status %d: %s\", resp.StatusCode, string(body))\n",
                    service.name, method_name
                ));
            } else {
                out.push_str(&format!(
                    "\t\treturn nil, fmt.Errorf(\"{}.{} failed with status %d: %s\", resp.StatusCode, string(body))\n",
                    service.name, method_name
                ));
            }
            out.push_str("\t}\n\n");

            if !output_type.is_empty() {
                let is_ptr = output_type.starts_with('*');
                let base_ty = if is_ptr {
                    &output_type[1..]
                } else {
                    &output_type
                };
                out.push_str(&format!("\tvar result {}\n", base_ty));
                out.push_str(
                    "\tif err := json.NewDecoder(resp.Body).Decode(&result); err != nil {\n",
                );
                out.push_str(
                    "\t\treturn nil, fmt.Errorf(\"failed to decode response: %w\", err)\n",
                );
                out.push_str("\t}\n");
                if is_ptr {
                    out.push_str("\treturn &result, nil\n");
                } else {
                    out.push_str("\treturn result, nil\n");
                }
            } else {
                out.push_str("\treturn nil\n");
            }

            out.push_str("}\n");
        }
    }

    fn type_to_go(ty: &Type) -> String {
        match ty {
            Type::Bool => "bool".to_string(),
            Type::String => "string".to_string(),
            Type::Int32 => "int32".to_string(),
            Type::Int64 => "int64".to_string(),
            Type::Float64 => "float64".to_string(),
            Type::Bytes => "[]byte".to_string(),
            Type::List(inner) => format!("[]{}", Self::type_to_go(inner)),
            Type::Map { key, value } => {
                format!("map[{}]{}", Self::type_to_go(key), Self::type_to_go(value))
            }
            Type::Optional(inner) => format!("*{}", Self::type_to_go(inner)),
            Type::Reference(name) => name.clone(),
        }
    }
}

fn to_pascal_case(s: &str) -> String {
    let mut out = String::new();
    let mut cap_next = true;
    for ch in s.chars() {
        if ch == '_' || ch == '-' {
            cap_next = true;
        } else if cap_next {
            out.extend(ch.to_uppercase());
            cap_next = false;
        } else {
            out.push(ch);
        }
    }

    // Common Go acronym casing
    match out.as_str() {
        "Id" => "ID".to_string(),
        "Url" => "URL".to_string(),
        "Api" => "API".to_string(),
        "Http" => "HTTP".to_string(),
        other => {
            if let Some(prefix) = other.strip_suffix("Id") {
                format!("{prefix}ID")
            } else if let Some(prefix) = other.strip_suffix("Url") {
                format!("{prefix}URL")
            } else if let Some(prefix) = other.strip_suffix("Api") {
                format!("{prefix}API")
            } else {
                other.to_string()
            }
        }
    }
}
