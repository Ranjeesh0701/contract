use crate::ir::{Contract, EnumType, Record, Service, Type, TypeAlias, TypeDefinition};

pub struct PythonGenerator;

impl PythonGenerator {
    pub fn generate(contract: &Contract) -> String {
        let mut out = String::new();

        let has_enums = contract
            .types
            .iter()
            .any(|t| matches!(t, TypeDefinition::Enum(_)));
        let has_records = contract
            .types
            .iter()
            .any(|t| matches!(t, TypeDefinition::Record(_)));
        let has_services = !contract.services.is_empty();

        let needs_field = contract.types.iter().any(|t| match t {
            TypeDefinition::Record(r) => r.fields.iter().any(|f| {
                let field_ident = Self::to_snake_case(&f.name);
                matches!(f.field_type, Type::Optional(_))
                    || field_ident != f.name
                    || f.description.is_some()
                    || f.deprecated.is_some()
            }),
            _ => false,
        });

        let needs_optional = contract.types.iter().any(|t| match t {
            TypeDefinition::Record(r) => r
                .fields
                .iter()
                .any(|f| Self::contains_optional(&f.field_type)),
            TypeDefinition::Alias(a) => Self::contains_optional(&a.target),
            _ => false,
        }) || contract.services.iter().any(|s| {
            s.operations.iter().any(|op| {
                op.input.as_ref().is_some_and(Self::contains_optional)
                    || op.output.as_ref().is_some_and(Self::contains_optional)
            })
        });

        out.push_str("# Code generated by contract platform. DO NOT EDIT.\n");
        out.push_str("from __future__ import annotations\n\n");

        // Standard library imports
        let mut stdlib_imports = Vec::new();
        if has_services {
            stdlib_imports.push("from abc import ABC, abstractmethod");
        }
        if has_enums {
            stdlib_imports.push("from enum import Enum");
        }
        if has_services {
            stdlib_imports.push("import json");
        }
        if needs_optional {
            stdlib_imports.push("from typing import Optional");
        }
        if has_services {
            stdlib_imports.push("import urllib.error");
            stdlib_imports.push("import urllib.request");
        }

        if !stdlib_imports.is_empty() {
            for imp in stdlib_imports {
                out.push_str(&format!("{}\n", imp));
            }
            out.push('\n');
        }

        // Third-party imports (Pydantic)
        if has_records {
            if needs_field {
                out.push_str("from pydantic import BaseModel, Field\n\n");
            } else {
                out.push_str("from pydantic import BaseModel\n\n");
            }
        }

        if let Some(ref desc) = contract.description {
            out.push_str(&format!("\"\"\"\n{}\n\"\"\"\n\n", desc));
        }

        for type_def in &contract.types {
            match type_def {
                TypeDefinition::Alias(alias) => Self::generate_alias(alias, &mut out),
                TypeDefinition::Enum(enm) => Self::generate_enum(enm, &mut out),
                TypeDefinition::Record(rec) => Self::generate_record(rec, &mut out),
            }
            out.push('\n');
        }

        for service in &contract.services {
            Self::generate_service(service, &mut out);
            out.push('\n');
        }

        if !contract.services.is_empty() {
            let client_name = format!("{}Client", contract.name);
            out.push_str(&format!("class {}:\n", client_name));
            out.push_str("    def __init__(self, base_url: str):\n");
            for service in &contract.services {
                let field_name = Self::to_snake_case(&service.name);
                out.push_str(&format!(
                    "        self.{} = {}Client(base_url)\n",
                    field_name, service.name
                ));
            }
            out.push('\n');
        }

        out
    }

    fn contains_optional(ty: &Type) -> bool {
        match ty {
            Type::Optional(_) => true,
            Type::List(inner) => Self::contains_optional(inner),
            Type::Map { key, value } => {
                Self::contains_optional(key) || Self::contains_optional(value)
            }
            _ => false,
        }
    }

    fn generate_alias(alias: &TypeAlias, out: &mut String) {
        if let Some(ref desc) = alias.description {
            out.push_str(&format!("\"\"\"\n{}\n\"\"\"\n", desc));
        }
        out.push_str(&format!(
            "{} = {}\n",
            alias.name,
            Self::type_to_python(&alias.target)
        ));
    }

    fn generate_enum(enm: &EnumType, out: &mut String) {
        out.push_str(&format!("class {}(str, Enum):\n", enm.name));
        if let Some(ref desc) = enm.description {
            out.push_str(&format!("    \"\"\"\n    {}\n    \"\"\"\n\n", desc));
        }

        for variant in &enm.variants {
            if let Some(ref desc) = variant.description {
                out.push_str(&format!("    # {}\n", desc));
            }
            out.push_str(&format!("    {} = \"{}\"\n", variant.name, variant.name));
        }
    }

    fn generate_record(rec: &Record, out: &mut String) {
        out.push_str(&format!("class {}(BaseModel):\n", rec.name));
        if let Some(ref desc) = rec.description {
            out.push_str(&format!("    \"\"\"\n    {}\n    \"\"\"\n\n", desc));
        }
        out.push_str("    model_config = {\"populate_by_name\": True}\n\n");

        if rec.fields.is_empty() {
            out.push_str("    pass\n");
            return;
        }

        for field in &rec.fields {
            let field_ident = Self::to_snake_case(&field.name);
            let py_type = Self::type_to_python(&field.field_type);
            let is_optional = matches!(field.field_type, Type::Optional(_));

            let mut field_args = Vec::new();
            if is_optional {
                field_args.push("default=None".to_string());
            }
            if field_ident != field.name {
                field_args.push(format!("alias=\"{}\"", field.name));
            }
            if let Some(ref desc) = field.description {
                field_args.push(format!("description=\"{}\"", desc.replace('"', "\\\"")));
            }
            if let Some(ref dep) = field.deprecated {
                field_args.push("deprecated=True".to_string());
                if field.description.is_none() {
                    field_args.push(format!(
                        "description=\"Deprecated: {}\"",
                        dep.replace('"', "\\\"")
                    ));
                }
            }

            if field_args.is_empty() {
                out.push_str(&format!("    {}: {}\n", field_ident, py_type));
            } else {
                out.push_str(&format!(
                    "    {}: {} = Field({})\n",
                    field_ident,
                    py_type,
                    field_args.join(", ")
                ));
            }
        }
    }

    fn generate_service(service: &Service, out: &mut String) {
        // 1. Abstract Base Class (Interface for server stubs)
        out.push_str(&format!("class {}(ABC):\n", service.name));
        if let Some(ref desc) = service.description {
            out.push_str(&format!("    \"\"\"\n    {}\n    \"\"\"\n\n", desc));
        }

        if service.operations.is_empty() {
            out.push_str("    pass\n\n");
        } else {
            for op in &service.operations {
                let method_name = Self::to_snake_case(&op.name);
                let input_param = match &op.input {
                    Some(ty) => format!(", input: {}", Self::type_to_python(ty)),
                    None => "".to_string(),
                };
                let output_type = match &op.output {
                    Some(ty) => Self::type_to_python(ty),
                    None => "None".to_string(),
                };

                out.push_str("    @abstractmethod\n");
                out.push_str(&format!(
                    "    def {}(self{}) -> {}:\n",
                    method_name, input_param, output_type
                ));
                if let Some(ref desc) = op.description {
                    out.push_str(&format!(
                        "        \"\"\"\n        {}\n        \"\"\"\n",
                        desc
                    ));
                }
                out.push_str("        pass\n\n");
            }
        }

        // 2. Concrete Client Class
        let client_name = format!("{}Client", service.name);
        out.push_str(&format!("class {}({}):\n", client_name, service.name));
        out.push_str("    def __init__(self, base_url: str):\n");
        out.push_str("        self.base_url = base_url.rstrip(\"/\")\n\n");

        for (idx, op) in service.operations.iter().enumerate() {
            if idx > 0 {
                out.push('\n');
            }
            if let Some(ref desc) = op.description {
                out.push_str(&format!("    \"\"\"\n    {}\n    \"\"\"\n", desc));
            }
            let method_name = Self::to_snake_case(&op.name);
            let has_input = op.input.is_some();
            let input_param = if has_input {
                format!(
                    ", input: {}",
                    Self::type_to_python(op.input.as_ref().unwrap())
                )
            } else {
                "".to_string()
            };
            let output_type = match &op.output {
                Some(ty) => Self::type_to_python(ty),
                None => "None".to_string(),
            };

            out.push_str(&format!(
                "    def {}(self{}) -> {}:\n",
                method_name, input_param, output_type
            ));
            if let Some(ref desc) = op.description {
                out.push_str(&format!(
                    "        \"\"\"\n        {}\n        \"\"\"\n",
                    desc
                ));
            }
            out.push_str(&format!(
                "        url = f\"{{self.base_url}}/{}/{}\"\n",
                service.name, op.name
            ));

            if has_input {
                out.push_str("        payload = input.model_dump(by_alias=True) if hasattr(input, \"model_dump\") else input\n");
                out.push_str("        data = json.dumps(payload).encode(\"utf-8\")\n");
            } else {
                out.push_str("        data = None\n");
            }

            out.push_str("        req = urllib.request.Request(\n");
            out.push_str("            url,\n");
            out.push_str("            data=data,\n");
            out.push_str("            headers={\"Content-Type\": \"application/json\"},\n");
            out.push_str("            method=\"POST\",\n");
            out.push_str("        )\n");

            out.push_str("        try:\n");
            out.push_str("            with urllib.request.urlopen(req) as resp:\n");
            if let Some(ret_ty) = &op.output {
                out.push_str("                raw = json.loads(resp.read().decode(\"utf-8\"))\n");
                match ret_ty {
                    Type::Reference(name) => {
                        out.push_str(&format!(
                            "                if hasattr({}, \"model_validate\"):\n",
                            name
                        ));
                        out.push_str(&format!(
                            "                    return {}.model_validate(raw)\n",
                            name
                        ));
                        out.push_str(&format!("                return {}(raw)\n", name));
                    }
                    Type::List(inner) => {
                        if let Type::Reference(name) = inner.as_ref() {
                            out.push_str(&format!(
                                "                if hasattr({}, \"model_validate\"):\n",
                                name
                            ));
                            out.push_str(&format!(
                                "                    return [{}.model_validate(item) for item in raw]\n",
                                name
                            ));
                        }
                        out.push_str("                return raw\n");
                    }
                    _ => {
                        out.push_str("                return raw\n");
                    }
                }
            } else {
                out.push_str("                return None\n");
            }

            out.push_str("        except urllib.error.HTTPError as err:\n");
            out.push_str(&format!(
                "            raise RuntimeError(f\"{}.{} failed with status {{err.code}}: {{err.read().decode('utf-8')}}\")\n",
                service.name, method_name
            ));
        }
    }

    fn type_to_python(ty: &Type) -> String {
        match ty {
            Type::Bool => "bool".to_string(),
            Type::String => "str".to_string(),
            Type::Int32 | Type::Int64 => "int".to_string(),
            Type::Float64 => "float".to_string(),
            Type::Bytes => "bytes".to_string(),
            Type::List(inner) => format!("list[{}]", Self::type_to_python(inner)),
            Type::Map { key, value } => format!(
                "dict[{}, {}]",
                Self::type_to_python(key),
                Self::type_to_python(value)
            ),
            Type::Optional(inner) => format!("Optional[{}]", Self::type_to_python(inner)),
            Type::Reference(name) => name.clone(),
        }
    }

    fn to_snake_case(s: &str) -> String {
        let mut result = String::new();
        for (i, ch) in s.chars().enumerate() {
            if ch.is_uppercase() {
                if i != 0 {
                    result.push('_');
                }
                result.extend(ch.to_lowercase());
            } else {
                result.push(ch);
            }
        }
        result
    }
}
