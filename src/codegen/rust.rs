use crate::ir::{Contract, EnumType, Record, Service, Type, TypeAlias, TypeDefinition};

pub struct RustGenerator;

impl RustGenerator {
    pub fn generate(contract: &Contract) -> String {
        let mut out = String::with_capacity(1024);

        out.push_str("// Code generated by contract platform. DO NOT EDIT.\n\n");
        out.push_str("use serde::{Deserialize, Serialize};\n\n");

        if let Some(ref desc) = contract.description {
            out.push_str(&format!("//! {}\n\n", desc));
        }

        for type_def in &contract.types {
            match type_def {
                TypeDefinition::Record(rec) => Self::generate_record(rec, &mut out),
                TypeDefinition::Enum(enm) => Self::generate_enum(enm, &mut out),
                TypeDefinition::Alias(alias) => Self::generate_alias(alias, &mut out),
            }
            out.push('\n');
        }

        for service in &contract.services {
            Self::generate_service(service, &mut out);
            out.push('\n');
        }

        if !contract.services.is_empty() {
            Self::generate_client_bundle(contract, &mut out);
        }

        out
    }

    fn rust_doc_and_dep(indent: &str, desc: Option<&str>, deprecated: Option<&str>) -> String {
        let mut s = String::new();
        if let Some(d) = desc {
            for line in d.lines() {
                s.push_str(&format!("{}/// {}\n", indent, line));
            }
        }
        if let Some(dep) = deprecated {
            s.push_str(&format!(
                "{}#[deprecated(note = \"{}\")]\n",
                indent,
                dep.replace('"', "\\\"")
            ));
        }
        s
    }

    fn generate_service(service: &Service, out: &mut String) {
        out.push_str(&Self::rust_doc_and_dep(
            "",
            service.description.as_deref(),
            service.deprecated.as_deref(),
        ));
        out.push_str(&format!("pub trait {} {{\n", service.name));
        for op in &service.operations {
            out.push_str(&Self::rust_doc_and_dep(
                "    ",
                op.description.as_deref(),
                op.deprecated.as_deref(),
            ));
            let fn_name = Self::to_snake_case(&op.name);
            let input_param = match &op.input {
                Some(ty) => format!(", input: {}", Self::type_to_rust(ty)),
                None => "".to_string(),
            };
            let ret_type = match &op.output {
                Some(ty) => format!(
                    "Result<{}, Box<dyn std::error::Error + Send + Sync>>",
                    Self::type_to_rust(ty)
                ),
                None => "Result<(), Box<dyn std::error::Error + Send + Sync>>".to_string(),
            };
            out.push_str(&format!(
                "    fn {}(&self{}) -> {};\n",
                fn_name, input_param, ret_type
            ));
        }
        out.push_str("}\n\n");

        let client_struct = format!("{}Client", service.name);
        out.push_str("#[derive(Debug, Clone)]\n");
        out.push_str(&format!("pub struct {} {{\n", client_struct));
        out.push_str("    pub base_url: String,\n");
        out.push_str("}\n\n");

        out.push_str(&format!("impl {} {{\n", client_struct));
        out.push_str("    pub fn new(base_url: impl Into<String>) -> Self {\n");
        out.push_str("        Self {\n");
        out.push_str("            base_url: base_url.into(),\n");
        out.push_str("        }\n");
        out.push_str("    }\n");

        for op in &service.operations {
            out.push('\n');
            out.push_str(&Self::rust_doc_and_dep(
                "    ",
                op.description.as_deref(),
                op.deprecated.as_deref(),
            ));
            let fn_name = Self::to_snake_case(&op.name);
            let input_param = match &op.input {
                Some(ty) => format!(", _input: {}", Self::type_to_rust(ty)),
                None => "".to_string(),
            };
            let ret_type = match &op.output {
                Some(ty) => format!(
                    "Result<{}, Box<dyn std::error::Error + Send + Sync>>",
                    Self::type_to_rust(ty)
                ),
                None => "Result<(), Box<dyn std::error::Error + Send + Sync>>".to_string(),
            };
            out.push_str(&format!(
                "    pub fn {}(&self{}) -> {} {{\n",
                fn_name, input_param, ret_type
            ));
            out.push_str(&format!(
                "        // Endpoint: {}/{}\n",
                service.name, op.name
            ));
            out.push_str("        todo!(\"Implement RPC transport call\")\n");
            out.push_str("    }\n");
        }
        out.push_str("}\n");
    }

    fn generate_client_bundle(contract: &Contract, out: &mut String) {
        let bundle_name = format!("{}Client", contract.name);
        out.push_str("#[derive(Debug, Clone)]\n");
        out.push_str(&format!("pub struct {} {{\n", bundle_name));
        for service in &contract.services {
            let field_name = Self::to_snake_case(&service.name);
            out.push_str(&format!(
                "    pub {}: {}Client,\n",
                field_name, service.name
            ));
        }
        out.push_str("}\n\n");

        out.push_str(&format!("impl {} {{\n", bundle_name));
        out.push_str("    pub fn new(base_url: impl Into<String>) -> Self {\n");
        out.push_str("        let url = base_url.into();\n");
        out.push_str("        Self {\n");
        for service in &contract.services {
            let field_name = Self::to_snake_case(&service.name);
            out.push_str(&format!(
                "            {}: {}Client::new(url.clone()),\n",
                field_name, service.name
            ));
        }
        out.push_str("        }\n");
        out.push_str("    }\n");
        out.push_str("}\n");
    }

    fn generate_record(rec: &Record, out: &mut String) {
        out.push_str(&Self::rust_doc_and_dep(
            "",
            rec.description.as_deref(),
            rec.deprecated.as_deref(),
        ));

        out.push_str("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n");
        out.push_str(&format!("pub struct {} {{\n", rec.name));

        for field in &rec.fields {
            out.push_str(&Self::rust_doc_and_dep(
                "    ",
                field.description.as_deref(),
                field.deprecated.as_deref(),
            ));

            let field_ident = Self::to_snake_case(&field.name);
            if field_ident != field.name {
                out.push_str(&format!("    #[serde(rename = \"{}\")]\n", field.name));
            }

            out.push_str(&format!(
                "    pub {}: {},\n",
                field_ident,
                Self::type_to_rust(&field.field_type)
            ));
        }

        out.push_str("}\n");
    }

    fn generate_enum(enm: &EnumType, out: &mut String) {
        out.push_str(&Self::rust_doc_and_dep(
            "",
            enm.description.as_deref(),
            enm.deprecated.as_deref(),
        ));

        out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]\n");
        out.push_str(&format!("pub enum {} {{\n", enm.name));

        for variant in &enm.variants {
            out.push_str(&Self::rust_doc_and_dep(
                "    ",
                variant.description.as_deref(),
                variant.deprecated.as_deref(),
            ));
            out.push_str(&format!("    {},\n", variant.name));
        }

        out.push_str("}\n");
    }

    fn generate_alias(alias: &TypeAlias, out: &mut String) {
        out.push_str(&Self::rust_doc_and_dep(
            "",
            alias.description.as_deref(),
            alias.deprecated.as_deref(),
        ));
        out.push_str(&format!(
            "pub type {} = {};\n",
            alias.name,
            Self::type_to_rust(&alias.target)
        ));
    }

    fn type_to_rust(ty: &Type) -> String {
        match ty {
            Type::Bool => "bool".to_string(),
            Type::String => "String".to_string(),
            Type::Int32 => "i32".to_string(),
            Type::Int64 => "i64".to_string(),
            Type::Float64 => "f64".to_string(),
            Type::Bytes => "Vec<u8>".to_string(),
            Type::List(inner) => format!("Vec<{}>", Self::type_to_rust(inner)),
            Type::Map { key, value } => format!(
                "std::collections::HashMap<{}, {}>",
                Self::type_to_rust(key),
                Self::type_to_rust(value)
            ),
            Type::Optional(inner) => format!("Option<{}>", Self::type_to_rust(inner)),
            Type::Reference(name) => name.clone(),
        }
    }

    fn to_snake_case(s: &str) -> String {
        let mut result = String::new();
        for (i, ch) in s.chars().enumerate() {
            if ch.is_uppercase() {
                if i != 0 {
                    result.push('_');
                }
                result.extend(ch.to_lowercase());
            } else {
                result.push(ch);
            }
        }
        result
    }
}
