use ir::{Contract, EnumType, Record, Service, Type, TypeAlias, TypeDefinition};

pub struct TypeScriptGenerator;

impl TypeScriptGenerator {
    pub fn generate(contract: &Contract) -> String {
        let mut out = String::new();

        out.push_str("// Code generated by contract platform. DO NOT EDIT.\n\n");

        if let Some(ref desc) = contract.description {
            out.push_str(&format!("/**\n * {}\n */\n", desc));
        }

        for type_def in &contract.types {
            match type_def {
                TypeDefinition::Record(rec) => Self::generate_record(rec, &mut out),
                TypeDefinition::Enum(enm) => Self::generate_enum(enm, &mut out),
                TypeDefinition::Alias(alias) => Self::generate_alias(alias, &mut out),
            }
            out.push('\n');
        }

        for service in &contract.services {
            Self::generate_service(service, &mut out);
            out.push('\n');
        }

        if !contract.services.is_empty() {
            let client_name = format!("{}Client", contract.name);
            out.push_str(&format!("export class {} {{\n", client_name));
            for service in &contract.services {
                let field_name = Self::to_camel_case(&service.name);
                out.push_str(&format!(
                    "  readonly {}: {}Client;\n",
                    field_name, service.name
                ));
            }
            out.push_str("\n  constructor(baseUrl: string, fetchFn: typeof fetch = fetch) {\n");
            for service in &contract.services {
                let field_name = Self::to_camel_case(&service.name);
                out.push_str(&format!(
                    "    this.{} = new {}Client(baseUrl, fetchFn);\n",
                    field_name, service.name
                ));
            }
            out.push_str("  }\n");
            out.push_str("}\n");
        }

        out
    }

    fn generate_record(rec: &Record, out: &mut String) {
        if let Some(ref desc) = rec.description {
            out.push_str(&format!("/**\n * {}\n */\n", desc));
        }
        out.push_str(&format!("export interface {} {{\n", rec.name));

        for field in &rec.fields {
            if let Some(ref desc) = field.description {
                out.push_str(&format!("  /**\n   * {}\n   */\n", desc));
            }

            let (is_optional, type_str) = match &field.field_type {
                Type::Optional(inner) => (true, Self::type_to_ts(inner)),
                other => (false, Self::type_to_ts(other)),
            };

            let opt_marker = if is_optional { "?" } else { "" };
            out.push_str(&format!("  {}{}: {};\n", field.name, opt_marker, type_str));
        }

        out.push_str("}\n");
    }

    fn generate_enum(enm: &EnumType, out: &mut String) {
        if let Some(ref desc) = enm.description {
            out.push_str(&format!("/**\n * {}\n */\n", desc));
        }
        out.push_str(&format!("export type {} =\n", enm.name));

        for (i, variant) in enm.variants.iter().enumerate() {
            let prefix = if i == 0 { "  " } else { "  | " };
            out.push_str(&format!("{}\"{}\"\n", prefix, variant.name));
        }
        out.push_str(";\n");
    }

    fn generate_alias(alias: &TypeAlias, out: &mut String) {
        if let Some(ref desc) = alias.description {
            out.push_str(&format!("/**\n * {}\n */\n", desc));
        }
        out.push_str(&format!(
            "export type {} = {};\n",
            alias.name,
            Self::type_to_ts(&alias.target)
        ));
    }

    fn generate_service(service: &Service, out: &mut String) {
        if let Some(ref desc) = service.description {
            out.push_str(&format!("/**\n * {}\n */\n", desc));
        }
        out.push_str(&format!("export interface {} {{\n", service.name));

        for op in &service.operations {
            if let Some(ref desc) = op.description {
                out.push_str(&format!("  /**\n   * {}\n   */\n", desc));
            }

            let input_param = match &op.input {
                Some(ty) => format!("input: {}", Self::type_to_ts(ty)),
                None => "".to_string(),
            };

            let output_type = match &op.output {
                Some(ty) => format!("Promise<{}>", Self::type_to_ts(ty)),
                None => "Promise<void>".to_string(),
            };

            let method_name = Self::to_camel_case(&op.name);
            out.push_str(&format!(
                "  {}({}): {};\n",
                method_name, input_param, output_type
            ));
        }

        out.push_str("}\n\n");

        let client_name = format!("{}Client", service.name);
        out.push_str(&format!(
            "export class {} implements {} {{\n",
            client_name, service.name
        ));
        out.push_str("  private baseUrl: string;\n");
        out.push_str("  private fetchFn: typeof fetch;\n\n");
        out.push_str("  constructor(baseUrl: string, fetchFn: typeof fetch = fetch) {\n");
        out.push_str("    this.baseUrl = baseUrl.replace(/\\/+$/, \"\");\n");
        out.push_str("    this.fetchFn = fetchFn;\n");
        out.push_str("  }\n\n");

        for (idx, op) in service.operations.iter().enumerate() {
            if idx > 0 {
                out.push('\n');
            }
            if let Some(ref desc) = op.description {
                out.push_str(&format!("  /**\n   * {}\n   */\n", desc));
            }
            let method_name = Self::to_camel_case(&op.name);
            let has_input = op.input.is_some();
            let input_param = if has_input {
                format!("input: {}", Self::type_to_ts(op.input.as_ref().unwrap()))
            } else {
                "".to_string()
            };

            let output_type = match &op.output {
                Some(ty) => Self::type_to_ts(ty),
                None => "void".to_string(),
            };

            out.push_str(&format!(
                "  async {}({}): Promise<{}> {{\n",
                method_name, input_param, output_type
            ));
            out.push_str(&format!(
                "    const url = `${{this.baseUrl}}/{}/{}`;\n",
                service.name, op.name
            ));

            let body_str = if has_input {
                "body: JSON.stringify(input),"
            } else {
                ""
            };

            out.push_str("    const res = await this.fetchFn(url, {\n");
            out.push_str("      method: \"POST\",\n");
            out.push_str("      headers: { \"Content-Type\": \"application/json\" },\n");
            if has_input {
                out.push_str(&format!("      {}\n", body_str));
            }
            out.push_str("    });\n");

            out.push_str("    if (!res.ok) {\n");
            out.push_str(&format!(
                "      throw new Error(`{}.{} failed with status ${{res.status}}: ${{await res.text()}}`);\n",
                service.name, method_name
            ));
            out.push_str("    }\n");

            if op.output.is_some() {
                out.push_str(&format!(
                    "    return (await res.json()) as {};\n",
                    output_type
                ));
            }

            out.push_str("  }\n");
        }

        out.push_str("}\n");
    }

    fn type_to_ts(ty: &Type) -> String {
        match ty {
            Type::Bool => "boolean".to_string(),
            Type::String => "string".to_string(),
            Type::Int32 | Type::Int64 | Type::Float64 => "number".to_string(),
            Type::Bytes => "Uint8Array".to_string(),
            Type::List(inner) => {
                let inner_ts = Self::type_to_ts(inner);
                if inner_ts.contains('|') {
                    format!("({})[]", inner_ts)
                } else {
                    format!("{}[]", inner_ts)
                }
            }
            Type::Map { key, value } => {
                format!(
                    "Record<{}, {}>",
                    Self::type_to_ts(key),
                    Self::type_to_ts(value)
                )
            }
            Type::Optional(inner) => format!("{} | null | undefined", Self::type_to_ts(inner)),
            Type::Reference(name) => name.clone(),
        }
    }

    fn to_camel_case(s: &str) -> String {
        let mut chars = s.chars();
        match chars.next() {
            None => String::new(),
            Some(first) => first.to_lowercase().collect::<String>() + chars.as_str(),
        }
    }
}
